import { AjaxResponse } from "@brandup/ui-ajax";

// HTTP 409 Conflict — сервер сообщает, что сессия редактирования устарела
// (закоммичена или отменена, например, в другой вкладке), и сохранение невозможно.
const HTTP_CONFLICT = 409;

// Защита от повторного показа: если несколько полей одновременно получат 409,
// сообщение и перезагрузка должны произойти один раз.
let handling = false;

// Возвращает true, если ответ — конфликт устаревшей сессии редактирования.
export const isEditConflict = (response: AjaxResponse): boolean =>
    response.status === HTTP_CONFLICT;

// Единая реакция на устаревшую сессию: уведомить пользователя и перезагрузить
// страницу, чтобы редактор переинициализировался со свежим editId.
// Вызывайте при получении 409 от любого content-эндпоинта.
export const handleEditConflict = (): void => {
    if (handling)
        return;
    handling = true;

    window.alert("Сессия редактирования устарела (страница была изменена или редактирование завершено в другом месте). Страница будет перезагружена.");

    window.location.reload();
};
